function naturalFileName(product: ProductNameSource): string {
  return product.cloudinaryId.split('/').pop() ?? product.cloudinaryId;
}

/** Construye una asignación estable de public ID de Cloudinary a nombre comercial. */
export function createCommercialProductNameMap(
  products: readonly ProductNameSource[],
): ReadonlyMap<string, string> {
  const groups = new Map<string, ProductNameSource[]>();

  for (const product of products) {
    const key = `${product.category}|${product.subcategory}`;
    const group = groups.get(key) ?? [];
    group.push(product);
    groups.set(key, group);
  }

  const names = new Map<string, string>();

  for (const [key, group] of groups) {
    const sorted = [...group].sort((a, b) =>
      naturalFileName(a).localeCompare(naturalFileName(b), 'es', {
        numeric: true,
        sensitivity: 'base',
      }),
    );
    const bouquetOffset = BOUQUET_NAME_OFFSETS[key];
    const groupNames = COMMERCIAL_GROUP_NAMES[key];

    sorted.forEach((product, index) => {
      const commercialName =
        bouquetOffset != null ? WOMEN_NAMES[bouquetOffset + index] : groupNames?.[index];

      if (commercialName) {
        names.set(product.cloudinaryId, commercialName);
      }
    });
  }

  return names;
}
